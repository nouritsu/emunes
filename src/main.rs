fn read_screen_state(cpu: &Cpu, frame: &mut [u8; FRAME_LEN]) -> bool {
    let mut frame_idx = 0;
    let mut update = false;
    for addr in SCREEN_START..SCREEN_END {
        let color_idx = cpu.mem_read(addr);
        let (b1, b2, b3) = color(color_idx).rgb();
        if frame[frame_idx] != b1 || frame[frame_idx + 1] != b2 || frame[frame_idx + 2] != b3 {
            frame[frame_idx] = b1;
            frame[frame_idx + 1] = b2;
            frame[frame_idx + 2] = b3;
            update = true;
        }
        frame_idx += 3;
    }
    update
}

fn handle_user_input(cpu: &mut Cpu, ep: &mut EventPump) {
    for event in ep.poll_iter() {
        match event {
            Event::Quit { .. }
            | Event::KeyDown {
                keycode: Some(Keycode::Escape),
                ..
            } => std::process::exit(0),
            Event::KeyDown {
                keycode: Some(key), ..
            } => {
                let dir = match key {
                    Keycode::W => Some(0x77),
                    Keycode::S => Some(0x73),
                    Keycode::A => Some(0x61),
                    Keycode::D => Some(0x64),
                    _ => None,
                };

                if let Some(dir) = dir {
                    cpu.mem_write(INPUT_ADDR, dir);
                }
            }
            _ => { /* do nothing */ }
        }
    }
}

fn color(byte: u8) -> Color {
    match byte {
        0 => sdl2::pixels::Color::BLACK,
        1 => sdl2::pixels::Color::WHITE,
        2 | 9 => sdl2::pixels::Color::GREY,
        3 | 10 => sdl2::pixels::Color::RED,
        4 | 11 => sdl2::pixels::Color::GREEN,
        5 | 12 => sdl2::pixels::Color::BLUE,
        6 | 13 => sdl2::pixels::Color::MAGENTA,
        7 | 14 => sdl2::pixels::Color::YELLOW,
        _ => sdl2::pixels::Color::CYAN,
    }
}
